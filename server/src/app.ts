import cors from 'cors';
import express from 'express';
import helmet from 'helmet';
import { env } from './config/env.js';
import { bookingRouter, healthRouter, serviceRouter, userRouter } from './container.js';
import { errorHandler } from './errors/error-handler.js';
import { apiRateLimit, authRateLimit } from './middleware/rate-limit.js';
import { notFoundHandler } from './middleware/not-found.js';
import { requestLogger } from './middleware/request-logger.js';

export const app = express();
app.use(requestLogger);
app.use(helmet());
app.use(cors({ origin: env.CLIENT_ORIGIN }));
app.use(express.json());
app.use('/api/health', healthRouter);
app.use('/api/users', authRateLimit, apiRateLimit, userRouter);
app.use('/api/services', apiRateLimit, serviceRouter);
app.use('/api/bookings', apiRateLimit, bookingRouter);
app.use(notFoundHandler);
app.use(errorHandler);
